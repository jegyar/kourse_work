def add_figure(doc, img_path, caption_text, width_cm=13.5):
    """Вставляет рисунок по центру, затем подпись по центру без точки на конце."""
    if os.path.exists(img_path):
        para_img = doc.add_paragraph()
        _fmt_para(para_img, align=WD_ALIGN_PARAGRAPH.CENTER,
                  first_indent_cm=0, line_spacing_pt=21,
                  space_before=6, space_after=0)
        run_img = para_img.add_run()
        run_img.add_picture(img_path, width=Cm(width_cm))
    else:
        para_err = doc.add_paragraph()
        run_err = para_err.add_run(f"[Рисунок недоступен: {os.path.basename(img_path)}]")
        _apply_run_font(run_err, italic=True)
        _fmt_para(para_err, align=WD_ALIGN_PARAGRAPH.CENTER, first_indent_cm=0)

    para_cap = doc.add_paragraph()
    run_cap = para_cap.add_run(caption_text)
    _apply_run_font(run_cap)
    _fmt_para(para_cap, align=WD_ALIGN_PARAGRAPH.CENTER,
              first_indent_cm=0, line_spacing_pt=21,
              space_before=0, space_after=6)
    return para_cap


