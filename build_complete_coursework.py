def make_table(doc, headers, rows, col_widths=None):
    """Создает таблицу по стандарту СТП БГУИР с центрированными заголовками 12pt."""
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER

    hdr_row = table.rows[0]
    for i, h in enumerate(headers):
        cell = hdr_row.cells[i]
        cell.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
        para = cell.paragraphs[0]
        para.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = para.add_run(h)
        _apply_run_font(run, bold=True, size_pt=12)
        fmt = para.paragraph_format
        fmt.space_before = Pt(2)
        fmt.space_after = Pt(2)
        fmt.line_spacing = Pt(18)
        fmt.first_line_indent = Pt(0)

    for ri, row_data in enumerate(rows):
        row = table.rows[ri + 1]
        for ci, cell_text in enumerate(row_data):
            cell = row.cells[ci]
            cell.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
            para = cell.paragraphs[0]
            para.alignment = WD_ALIGN_PARAGRAPH.LEFT
            run = para.add_run(str(cell_text))
            _apply_run_font(run, size_pt=12)
            fmt = para.paragraph_format
            fmt.space_before = Pt(2)
            fmt.space_after = Pt(2)
            fmt.line_spacing = Pt(18)
            fmt.first_line_indent = Pt(0)

    if col_widths:
        for r in table.rows:
            for ci, w in enumerate(col_widths):
                r.cells[ci].width = Cm(w)

    para_post = doc.add_paragraph()
    _fmt_para(para_post, first_indent_cm=0, line_spacing_pt=6)
    return table


def add_code_listing(doc, code_text):
    """Добавляет блок кода в моноширинном шрифте для листинга в приложении."""
    for line in code_text.splitlines():
        para = doc.add_paragraph()
        run = para.add_run(line if line.strip() else " ")
        _apply_run_font(run, font_name="Courier New", size_pt=10)
        _fmt_para(para, align=WD_ALIGN_PARAGRAPH.LEFT, first_indent_cm=0,
                  line_spacing_pt=13, space_before=0, space_after=0)


