    # ВВЕДЕНИЕ (ровно на 1 страницу)
    # ========================================================
    add_h1("ВВЕДЕНИЕ", is_centered=True)

    add_para("Сфера розничной торговли автомобильными запасными частями и компонентами отличается обширной номенклатурой и постоянным спросом. В условиях высокой конкуренции ручная обработка заявок и разрозненный складской учет приводят к задержкам подбора деталей, пересортице и ошибкам резервирования. Возникает объективная необходимость во внедрении автоматизированной информационной системы, обеспечивающей централизованный учет номенклатуры, контроль остатков и сквозное сопровождение клиентских заказов.")

    add_para("Управление каталогом автозапчастей и корзиной покупателя создает непрерывный поток запросов с поиском и фильтрацией по маркам, моделям и категориям. Надежное функционирование системы требует применения реляционной СУБД. Реляционная модель гарантирует ссылочную целостность между учетными записями, товарами, заказами и платежами. Оформление покупки опирается на строгую транзакционную изоляцию: списание складских остатков, фиксация отпускных цен и сохранение данных доставки должны выполняться атомарно, исключая коллизии при одновременном обращении клиентов.")

    add_para("Цель курсового проекта – проектирование и разработка автоматизированной информационной системы управления интернет-магазином автозапчастей, обеспечивающей учет номенклатуры, клиентскую корзину, транзакционную обработку заказов, многоформатный обмен данными и аналитическую отчетность.")

    add_para("Для достижения цели поставлены следующие задачи:")
    add_bullet("исследовать предметную область торговли автозапчастями и провести анализ систем-аналогов;")
    add_bullet("спроектировать концептуальную, логическую и физическую схемы базы данных;")
    add_bullet("разработать серверные модули работы с СУБД, обработки заказов, обмена данными и генерации отчетов;")
    add_bullet("реализовать пользовательский веб-интерфейс и составить руководство пользователя и администратора.")

    # Разрыв страницы перед разделом 1 (ровно после 1 страницы Введения)
    doc.add_page_break()

    # ========================================================
    # 1 ОБЗОР ИССЛЕДУЕМОЙ ОБЛАСТИ
    # ========================================================
    add_h1("1 ОБЗОР ИССЛЕДУЕМОЙ ОБЛАСТИ")

    # 1.1 Описание предметной области
    add_h2("1.1 Описание предметной области")

    add_para("Рынок автомобильных запасных частей и компонентов образует динамичный сектор розничной электронной коммерции. В отличие от типовых потребительских товаров, номенклатура автозапчастей насчитывает сотни тысяч наименований и охватывает широкий спектр категорий: детали двигателя, элементы подвески, тормозной системы, трансмиссии, электрооборудование и расходные материалы. Наряду с оригинальными компонентами на рынке обращаются лицензионные аналоги сторонних брендов с различными характеристиками и ценами [1].")

    add_para("В бизнес-процессах интернет-магазина автозапчастей участвуют две основные группы пользователей: покупатели и администраторы. Покупателям (автовладельцам и мастерам сервисных центров) необходим оперативный поиск деталей по марке и модели автомобиля, бренду и категории, добавление позиций в корзину и быстрое оформление заказа. Администраторы и складские менеджеры выполняют ведение номенклатуры, контроль складских запасов, управление статусами заказов, импорт и экспорт каталогов, а в завершение рабочих циклов формируют аналитическую отчетность.")

    add_para("Ведение торговли без средств автоматизации приводит к существенным издержкам. Ручной учет сопровождается длительным поиском совместимых деталей среди обширного ассортимента и риском продажи отсутствующего товара при одновременном оформлении одного физического экземпляра несколькими покупателями. Изменение базовых цен номенклатуры задним числом искажает финансовую отчетность из-за отсутствия фиксации цен сделки в момент заказа. Ручное обновление прайс-листов от внешних поставщиков отличается высокой трудоемкостью, а руководству не хватает оперативной аналитики по выручке, стадиям заказов и наиболее востребованным позициям.")

