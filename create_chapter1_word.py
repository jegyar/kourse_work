    add_para("Главный процесс системы заключается в транзакционном переводе выбранных товаров из корзины в оформленный заказ. В рамках единой транзакции СУБД проверяется наличие необходимого количества деталей на складе, фиксируются закупочные цены позиций, списываются складские запасы и регистрируются реквизиты доставки и оплаты. При отмене заказа система автоматически возвращает зарезервированные товары на склад.")

    # 1.2 Обзор аналогов
    add_h2("1.2 Обзор аналогов")

    add_para("Для сопоставления архитектурных и функциональных решений выбраны три профильные системы торговли автомобильными деталями: федеральный интернет-магазин новых компонентов Exist.ru, ведущий белорусский портал поиска автозапчастей Bumper.by и сетевой интернет-магазин Autodoc.ru. Каждый аналог рассмотрен по единой схеме: назначение, принцип функционирования, достоинства и недостатки.")

    add_h3("1.2.1 Специализированный интернет-магазин автозапчастей Exist.ru")
    # keep_with_next=True чтобы фраза со ссылкой на рисунок никогда не отрывалась от самого рисунка
    add_para("Exist.ru – одна из крупнейших торговых платформ на рынке новых автомобильных запчастей и расходных материалов. Поиск деталей организован по артикулам, VIN-коду транспортного средства и структурированным каталогам автопроизводителей с матрицами кросс-кодировок аналогов [1]. Главная страница сайта Exist.ru показана на рисунке 1.1.", keep_with_next=True)

    exist_img = os.path.join(os.getcwd(), 'chapter_1', 'screenshots_placeholders', 'exist_screen.png')
    add_figure(exist_img, "Рисунок 1.1 – Главная страница сайта Exist.ru")

    add_para("К достоинствам системы Exist.ru относятся обширная номенклатурная база оригинальных деталей и сертифицированных заменителей, развитые алгоритмы подбора по идентификационному номеру автомобиля и разветвленная сеть пунктов выдачи заказов. Недостатки решения заключаются в закрытом исходном коде, исключающем локальное внедрение для независимого магазина, высокой ресурсоемкости инфраструктуры и отсутствии простых инструментов прямого обмена каталогом в открытых форматах.")

    add_h3("1.2.2 Портал поиска автозапчастей Bumper.by")
    # keep_with_next=True чтобы фраза со ссылкой на рисунок никогда не отрывалась от самого рисунка
    add_para("Bumper.by – специализированный белорусский интернет-портал, агрегирующий предложения по продаже контрактных, б/у и новых автозапчастей от сотен авторазборок и торговых складов Беларуси [2]. Поиск позиций выполняется по марке, модели, году выпуска автомобиля, типу кузова, узлу и агрегату. Интерфейс поиска автозапчастей сайта Bumper.by показан на рисунке 1.2.", keep_with_next=True)

    bumper_img = os.path.join(os.getcwd(), 'chapter_1', 'screenshots_placeholders', 'bumper_screen.png')
    add_figure(bumper_img, "Рисунок 1.2 – Интерфейс поиска автозапчастей сайта Bumper.by")

    add_para("Достоинствами портала Bumper.by выступают крупнейшая база автозапчастей в наличии на складах в Республике Беларусь, публикация реальных фотографий конкретных деталей и прямые контакты продавцов. Ограничения площадки связаны с отсутствием единой онлайн-корзины и сквозного оформления заказов, отсутствием строгого контроля актуальности складских остатков в реальном времени и невозможностью автоматического формирования первичных документов и складской отчетности.")

    add_h3("1.2.3 Интернет-магазин автозапчастей Autodoc.ru")
    # keep_with_next=True чтобы фраза со ссылкой на рисунок никогда не отрывалась от самого рисунка
    add_para("Autodoc.ru – популярная торговая сеть и интернет-магазин автозапчастей, ориентированный на розничные и оптовые онлайн-продажи [3]. Система обеспечивает регистрацию личного кабинета, подбор деталей, корзину, пошаговое оформление покупки и отслеживание доставки. Каталог деталей сайта Autodoc.ru показан на рисунке 1.3.", keep_with_next=True)

    autodoc_img = os.path.join(os.getcwd(), 'chapter_1', 'screenshots_placeholders', 'autodoc_screen.png')
    add_figure(autodoc_img, "Рисунок 1.3 – Каталог деталей сайта Autodoc.ru")

    add_para("Среди достоинств системы Autodoc.ru выделяются продуманный пользовательский интерфейс витрины и корзины, прозрачное информирование покупателя о стадиях транспортировки и развитая система клиентских скидок. В качестве недостатков отмечаются закрытая проприетарная платформа без возможности локальной адаптации, отсутствие открытого реляционного интерфейса к структуре базы данных и нехватка гибкого пакетного обмена каталогами в форматах CSV, JSON и XML для внешних систем.")

    add_h3("1.2.4 Сравнительный анализ систем-аналогов")
    add_para("Сопоставление рассмотренных систем приведено в таблице 1.1.")

    # Подпись таблицы
    p_tab_cap = doc.add_paragraph()
    p_tab_cap.alignment = WD_ALIGN_PARAGRAPH.LEFT
    p_tab_cap.paragraph_format.first_line_indent = Cm(1.25)
    p_tab_cap.paragraph_format.space_before = Pt(8)
    p_tab_cap.paragraph_format.space_after = Pt(4)
    p_tab_cap.paragraph_format.keep_with_next = True
    r_tab = p_tab_cap.add_run("Таблица 1.1 – Сравнительный анализ систем-аналогов")
    r_tab.font.name = 'Times New Roman'
    r_tab.font.size = Pt(14)

    # Таблица 1.1
    table_data = [
        ["Критерий", "Exist.ru", "Bumper.by", "Autodoc.ru"],
        ["Модель системы", "Сетевой интернет-магазин", "Агрегатор объявлений", "Сетевой интернет-магазин"],
        ["Встроенная корзина и заказ", "Реализовано", "Отсутствует", "Реализовано"],
        ["Транзакционный учет остатков", "Реализовано", "Отсутствует", "Реализовано"],
        ["Пакетный обмен (CSV, JSON, XML)", "Ограничено", "Отсутствует", "Ограничено"],
        ["Аналитические отчеты (PDF, Excel, Word)", "Базовые формы", "Отсутствует", "Базовые накладные"],
        ["Доступность для локального развертывания", "Отсутствует", "Отсутствует", "Отсутствует"],
        ["Мультиязычный интерфейс", "Региональный", "Только русский", "Только русский"]
    ]

    table = doc.add_table(rows=len(table_data), cols=4)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.style = 'Table Grid'

    col_widths = [Cm(4.5), Cm(4.0), Cm(4.0), Cm(4.0)]

    for row_idx, row_data in enumerate(table_data):
        row = table.rows[row_idx]
        trPr = row._tr.get_or_add_trPr()
        trPr.append(parse_xml(r'<w:cantSplit xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"/>'))

        for col_idx, cell_value in enumerate(row_data):
            cell = row.cells[col_idx]
            cell.width = col_widths[col_idx]
            set_cell_margins(cell, top=100, bottom=100, left=150, right=150)
            cell.vertical_alignment = WD_ALIGN_VERTICAL.CENTER

            p_cell = cell.paragraphs[0]
            p_cell.paragraph_format.space_before = Pt(0)
            p_cell.paragraph_format.space_after = Pt(0)
            p_cell.paragraph_format.line_spacing = 1.0
            p_cell.paragraph_format.first_line_indent = Cm(0)

            run_cell = p_cell.add_run(cell_value)
            run_cell.font.name = 'Times New Roman'
            run_cell.font.size = Pt(11) if row_idx > 0 else Pt(11.5)

            if row_idx == 0:
                p_cell.alignment = WD_ALIGN_PARAGRAPH.CENTER
                run_cell.bold = True
                shd = parse_xml(r'<w:shd {} w:fill="F2F2F2"/>'.format(nsdecls('w')))
                cell._tc.get_or_add_tcPr().append(shd)
            else:
                p_cell.alignment = WD_ALIGN_PARAGRAPH.LEFT

    # Абзацы после таблицы
